#!/usr/bin/env bun
/**
 * 界面文案的机器翻译桥:en 基线 ↔ `scripts/i18n-mt`(Python,qwen-mt)↔ 运行时生成模块。
 *
 *   bun scripts/i18n-messages.ts extract    # 打印 {"units": {"<unitKey>": "<en 文本>"}}(稳定遍历序)
 *   bun scripts/i18n-messages.ts generate   # 按 src/i18n/locales/<lang>.json 重写 src/i18n/locales/<lang>/<ns>.ts
 *
 * 只读 `src/i18n/messages/*.ts` 的源码(TypeScript 编译器 API),不执行它们,所以函数文案
 * 也能按字面量逐条翻译,逻辑(三元、复数判断、模板插值)原样保留。
 *
 * 翻译单元(unit)
 * - unitKey = `<ns>.<属性点路径>`;数组元素用下标段(`faq.items.3.q`)。
 * - 属性值本身是字符串字面量 → 键即路径;函数 / 括号 / 三元 / `+` 等「输出位置」里的字面量 →
 *   `<路径>#<n>`,n 为该属性值内按源码顺序的 0 起序号。属性值本身是模板字面量时它取路径键,
 *   其 `${}` 表达式里嵌套的可译字面量从 `#0` 起编号。
 * - 模板字面量:每个 `${expr}` 依次换成 `{0}`、`{1}`…(每个字面量各自编号);嵌套在 `${}` 里的字面量另成单元。
 * - 可译字面量只看输出位置:属性值本身,或仅经 ParenthesizedExpression、ConditionalExpression 两支、
 *   `+` 操作数、可译模板的 `${}` 表达式、箭头/函数表达式的返回表达式、数组元素、嵌套对象属性值到达。
 *   比较操作数、调用实参(`.join(", ")`、`toLocaleString("en-US")`)、条件表达式的条件一律原样保留。
 *
 * 生成模块:把 en 对象的源码文本按节点位置拼入译文,不在译文库里的单元保留 en 原文;
 * 模块级辅助常量原样复制,顶部只 `import type` 对应的 messages 模块(运行时不成环)。
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { MT_LANGS } from "../src/i18n/config";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MESSAGES_DIR = join(ROOT, "src/i18n/messages");
const LOCALES_DIR = join(ROOT, "src/i18n/locales");
const HEADER_PREFIX = "// generated by scripts/i18n-messages.ts";

type LiteralNode = ts.StringLiteral | ts.NoSubstitutionTemplateLiteral | ts.TemplateExpression;

interface Unit {
  key: string;
  /** 提取文本:模板里的 `${expr}` 已换成 `{0}`、`{1}`…,其余为已解析(cooked)的字面量内容。 */
  text: string;
  node: LiteralNode;
  /** 模板的 `${}` 表达式,与 `{N}` 一一对应;非模板为空。 */
  exprs: readonly ts.Expression[];
  /** 直接嵌套在本模板 `${}` 里的可译单元(源码序)。 */
  children: Unit[];
}

interface MessageModule {
  ns: string;
  source: ts.SourceFile;
  en: ts.ObjectLiteralExpression;
  /** 全部单元,源码(前序)顺序。 */
  units: Unit[];
  /** 不嵌套在任何模板 `${}` 内的单元。 */
  roots: Unit[];
  /** 字面量(模板 / 含续行的字符串)内部的行首偏移:这些行的缩进是内容,生成时不能缩进调整。 */
  literalLines: ReadonlySet<number>;
}

function fail(source: ts.SourceFile, node: ts.Node, message: string): never {
  const { line, character } = source.getLineAndCharacterOfPosition(node.getStart(source));
  throw new Error(`${source.fileName}:${line + 1}:${character + 1} ${message}`);
}

function isLiteralNode(node: ts.Node): node is LiteralNode {
  return ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) || ts.isTemplateExpression(node);
}

function unwrapParens(node: ts.Expression): ts.Expression {
  let cur = node;
  while (ts.isParenthesizedExpression(cur)) cur = cur.expression;
  return cur;
}

function propertySegment(source: ts.SourceFile, name: ts.PropertyName): string {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) return name.text;
  return fail(source, name, "文案对象只支持标识符 / 字符串 / 数字属性名");
}

/** 函数体里属于「输出位置」的 return 表达式(不进入嵌套函数)。 */
function returnExpressions(body: ts.Block): ts.Expression[] {
  const found: ts.Expression[] = [];
  const visit = (node: ts.Node): void => {
    if (ts.isFunctionLike(node) || ts.isClassLike(node)) return;
    if (ts.isReturnStatement(node)) {
      if (node.expression) found.push(node.expression);
      return;
    }
    ts.forEachChild(node, visit);
  };
  ts.forEachChild(body, visit);
  return found;
}

class Collector {
  readonly units: Unit[] = [];
  readonly roots: Unit[] = [];
  private readonly seen = new Set<string>();

  constructor(
    private readonly ns: string,
    private readonly source: ts.SourceFile,
  ) {}

  object(obj: ts.ObjectLiteralExpression, path: readonly string[]): void {
    for (const prop of obj.properties) {
      if (!ts.isPropertyAssignment(prop)) fail(this.source, prop, "文案对象只支持 `key: value` 属性(不支持简写 / 展开 / 方法)");
      this.value(prop.initializer, [...path, propertySegment(this.source, prop.name)]);
    }
  }

  private value(raw: ts.Expression, path: readonly string[]): void {
    const node = unwrapParens(raw);
    if (ts.isObjectLiteralExpression(node)) return this.object(node, path);
    if (ts.isArrayLiteralExpression(node)) {
      node.elements.forEach((element, index) => {
        if (ts.isSpreadElement(element) || ts.isOmittedExpression(element)) fail(this.source, element, "文案数组不支持展开 / 空位");
        this.value(element, [...path, String(index)]);
      });
      return;
    }
    const base = `${this.ns}.${path.join(".")}`;
    const ctx: WalkContext = { base, counter: { next: 0 }, plain: isLiteralNode(node) ? node : null, parent: null };
    this.walk(node, ctx);
  }

  /** 输出位置遍历:只进入契约列出的节点类型,其余原样不译。 */
  private walk(node: ts.Node, ctx: WalkContext): void {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      this.add(node, node.text, [], ctx);
    } else if (ts.isTemplateExpression(node)) {
      const exprs = node.templateSpans.map((span) => span.expression);
      if ([node.head, ...node.templateSpans.map((span) => span.literal)].some((piece) => /\{\d+\}/.test(piece.text))) {
        fail(this.source, node, "含 `${}` 的模板里不能再出现字面量 `{数字}`,会与占位符混淆");
      }
      let text = node.head.text;
      node.templateSpans.forEach((span, index) => {
        text += `{${index}}${span.literal.text}`;
      });
      const unit = this.add(node, text, exprs, ctx);
      const inner: WalkContext = { ...ctx, parent: unit };
      for (const expr of exprs) this.walk(expr, inner);
    } else if (ts.isParenthesizedExpression(node)) {
      this.walk(node.expression, ctx);
    } else if (ts.isConditionalExpression(node)) {
      this.walk(node.whenTrue, ctx);
      this.walk(node.whenFalse, ctx);
    } else if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.PlusToken) {
      this.walk(node.left, ctx);
      this.walk(node.right, ctx);
    } else if (ts.isArrowFunction(node) || ts.isFunctionExpression(node)) {
      if (ts.isBlock(node.body)) {
        for (const expr of returnExpressions(node.body)) this.walk(expr, ctx);
      } else {
        this.walk(node.body, ctx);
      }
    } else if (ts.isArrayLiteralExpression(node)) {
      for (const element of node.elements) this.walk(element, ctx);
    } else if (ts.isObjectLiteralExpression(node)) {
      for (const prop of node.properties) {
        if (ts.isPropertyAssignment(prop)) this.walk(prop.initializer, ctx);
      }
    }
  }

  private add(node: LiteralNode, text: string, exprs: readonly ts.Expression[], ctx: WalkContext): Unit {
    const key = ctx.plain === node ? ctx.base : `${ctx.base}#${ctx.counter.next++}`;
    if (this.seen.has(key)) fail(this.source, node, `重复的 unitKey:${key}`);
    this.seen.add(key);
    const unit: Unit = { key, text, node, exprs, children: [] };
    this.units.push(unit);
    (ctx.parent ? ctx.parent.children : this.roots).push(unit);
    return unit;
  }
}

interface WalkContext {
  base: string;
  /** 同一属性值内共享的 `#n` 计数器(嵌套模板的子上下文沿用同一个)。 */
  counter: { next: number };
  /** 属性值本身就是这个字面量时取不带 `#n` 的路径键。 */
  plain: LiteralNode | null;
  parent: Unit | null;
}

function findDefineMessages(source: ts.SourceFile, ns: string): ts.CallExpression {
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const decl of statement.declarationList.declarations) {
      const init = decl.initializer;
      if (init && ts.isCallExpression(init) && ts.isIdentifier(init.expression) && init.expression.text === "defineMessages") return init;
    }
  }
  throw new Error(`${ns}.ts 缺少顶层 defineMessages(...) 调用`);
}

/** 字面量内部(含字符串续行)每个换行之后的行首偏移。 */
function literalLineStarts(source: ts.SourceFile): Set<number> {
  const starts = new Set<number>();
  const visit = (node: ts.Node): void => {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) {
      for (let i = node.getStart(source); i < node.end; i++) {
        if (source.text[i] === "\n") starts.add(i + 1);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return starts;
}

function loadModule(file: string): MessageModule {
  const ns = basename(file, ".ts");
  const source = ts.createSourceFile(file, readFileSync(file, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const call = findDefineMessages(source, ns);
  const [nsArg, body] = call.arguments;
  if (!nsArg || !ts.isStringLiteral(nsArg) || nsArg.text !== ns) fail(source, call, `defineMessages 第一个参数必须是命名空间字符串 "${ns}"(与文件名一致)`);
  if (!body || !ts.isObjectLiteralExpression(body)) fail(source, call, "defineMessages 第二个参数必须是 { en, zh } 对象字面量");
  const enProp = body.properties.find((prop): prop is ts.PropertyAssignment => ts.isPropertyAssignment(prop) && propertySegment(source, prop.name) === "en");
  if (!enProp || !ts.isObjectLiteralExpression(enProp.initializer)) fail(source, body, "缺少 en 对象字面量");
  const collector = new Collector(ns, source);
  collector.object(enProp.initializer, []);
  return { ns, source, en: enProp.initializer, units: collector.units, roots: collector.roots, literalLines: literalLineStarts(source) };
}

function loadModules(): MessageModule[] {
  return readdirSync(MESSAGES_DIR)
    .filter((name) => name.endsWith(".ts"))
    .sort()
    .map((name) => loadModule(join(MESSAGES_DIR, name)));
}

// ───────────────────────── extract ─────────────────────────

function extract(): void {
  const units: Record<string, string> = {};
  for (const mod of loadModules()) {
    for (const unit of mod.units) units[unit.key] = unit.text;
  }
  process.stdout.write(`${JSON.stringify({ units }, null, 2)}\n`);
}

// ───────────────────────── generate ─────────────────────────

const PLACEHOLDER = /\{([A-Za-z0-9_.]+)\}/g;

function placeholderCounts(text: string): string {
  const counts = new Map<string, number>();
  for (const match of text.matchAll(PLACEHOLDER)) counts.set(match[1], (counts.get(match[1]) ?? 0) + 1);
  return [...counts].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).join("|");
}

function escapeString(text: string, quote: string): string {
  let out = "";
  for (const ch of text) {
    if (ch === "\\") out += "\\\\";
    else if (ch === quote) out += `\\${quote}`;
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\u2028" || ch === "\u2029") out += `\\u${ch.charCodeAt(0).toString(16)}`;
    else if (ch < " ") out += `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`;
    else out += ch;
  }
  return out;
}

function escapeTemplate(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${").replace(/\r/g, "\\r");
}

class Renderer {
  constructor(
    private readonly mod: MessageModule,
    private readonly store: Readonly<Record<string, string>>,
    private readonly lang: string,
    readonly stats: { applied: number },
  ) {}

  /** 译文有效才返回:非空字符串且占位符与 en 一致,否则回退 en。 */
  private translation(unit: Unit): string | null {
    const raw = this.store[unit.key];
    if (typeof raw !== "string" || raw === "") return null;
    if (placeholderCounts(raw) !== placeholderCounts(unit.text)) {
      console.warn(`[i18n] ${this.lang} ${unit.key}: 占位符与 en 不一致,保留 en 原文`);
      return null;
    }
    return raw;
  }

  /** en 对象在 `defineMessages({` 里多缩进了一级,搬到模块顶层时去掉(字面量内部的行不动)。 */
  private dedent(slice: string, offset: number): string {
    let out = "";
    let last = 0;
    for (let i = slice.indexOf("\n"); i >= 0; i = slice.indexOf("\n", i + 1)) {
      if (this.mod.literalLines.has(offset + i + 1) || !slice.startsWith("  ", i + 1)) continue;
      out += slice.slice(last, i + 1);
      last = i + 3;
    }
    return out + slice.slice(last);
  }

  /** 渲染 [start, end) 的源码,把其中(互不嵌套的)单元换成译文。 */
  private splice(start: number, end: number, units: readonly Unit[]): string {
    const text = this.mod.source.text;
    let out = "";
    let pos = start;
    for (const unit of units) {
      out += this.dedent(text.slice(pos, unit.node.getStart(this.mod.source)), pos) + this.unit(unit);
      pos = unit.node.end;
    }
    return out + this.dedent(text.slice(pos, end), pos);
  }

  private unit(unit: Unit): string {
    const { node } = unit;
    const source = this.mod.source;
    const translated = this.translation(unit);
    if (translated !== null) this.stats.applied += 1;
    if (ts.isTemplateExpression(node)) {
      if (translated === null) return this.splice(node.getStart(source), node.end, unit.children);
      let out = "`";
      let last = 0;
      for (const match of translated.matchAll(/\{(\d+)\}/g)) {
        const expr = unit.exprs[Number(match[1])];
        if (!expr) continue;
        out += escapeTemplate(translated.slice(last, match.index));
        const nested = unit.children.filter((child) => child.node.getStart(source) >= expr.getStart(source) && child.node.end <= expr.end);
        out += `\${${this.splice(expr.getStart(source), expr.end, nested)}}`;
        last = match.index + match[0].length;
      }
      return `${out}${escapeTemplate(translated.slice(last))}\``;
    }
    if (translated === null) return node.getText(source);
    if (ts.isNoSubstitutionTemplateLiteral(node)) return `\`${escapeTemplate(translated)}\``;
    const quote = source.text[node.getStart(source)];
    return `${quote}${escapeString(translated, quote)}${quote}`;
  }

  object(): string {
    return this.splice(this.mod.en.getStart(this.mod.source), this.mod.en.end, this.mod.roots);
  }
}

/** messages 模块的相对 import 搬到 locales/<lang>/ 下要加两层;`../define` 由生成模块自己取代。 */
function rewriteImport(statement: ts.ImportDeclaration, source: ts.SourceFile): string | null {
  const spec = statement.moduleSpecifier;
  if (!ts.isStringLiteral(spec)) return statement.getText(source);
  if (spec.text === "../define") return null;
  let target = spec.text;
  if (target.startsWith("../")) target = `../../${target.slice(3)}`;
  else if (target.startsWith("./")) target = `../../messages/${target.slice(2)}`;
  const text = statement.getText(source);
  const quote = text[spec.getStart(source) - statement.getStart(source)];
  return text.slice(0, spec.getStart(source) - statement.getStart(source)) + quote + target + quote + text.slice(spec.end - statement.getStart(source));
}

function renderModule(mod: MessageModule, lang: string, store: Readonly<Record<string, string>>, stats: { applied: number }): string {
  const { source, ns } = mod;
  const imports: string[] = [`import type { ${ns} } from "../../messages/${ns}";`];
  const helpers: string[] = [];
  for (const statement of source.statements) {
    if (ts.isImportDeclaration(statement)) {
      const rewritten = rewriteImport(statement, source);
      if (rewritten) imports.push(rewritten);
    } else if (!ts.isVariableStatement(statement) || !statement.declarationList.declarations.some((decl) => decl.initializer && ts.isCallExpression(decl.initializer) && ts.isIdentifier(decl.initializer.expression) && decl.initializer.expression.text === "defineMessages")) {
      // 模块级辅助常量 / 函数(如 legal.ts 的 ext、BILLING_MAIL)en 对象会引用,原样带上;导出的类型别名不带。
      const exported = ts.canHaveModifiers(statement) && ts.getModifiers(statement)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
      if (!exported) helpers.push(source.text.slice(statement.getStart(source, true), statement.end));
    }
  }
  const body = new Renderer(mod, store, lang, stats).object();
  return [
    `${HEADER_PREFIX} — do not edit; edit src/i18n/locales/${lang}.json`,
    ...imports,
    "",
    ...(helpers.length > 0 ? [helpers.join("\n"), ""] : []),
    `export default ${body} satisfies (typeof ${ns})["en"];`,
    "",
  ].join("\n");
}

function loadStore(lang: string): Record<string, string> {
  const file = join(LOCALES_DIR, `${lang}.json`);
  if (!existsSync(file)) return {};
  const parsed: unknown = JSON.parse(readFileSync(file, "utf8"));
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) throw new Error(`${file} 必须是 { "<unitKey>": "<译文>" } 平铺对象`);
  return parsed as Record<string, string>;
}

function writeIfChanged(file: string, content: string): boolean {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return false;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  return true;
}

function generate(): void {
  const modules = loadModules();
  const stats = { applied: 0 };
  let written = 0;
  for (const lang of MT_LANGS) {
    const store = loadStore(lang);
    const dir = join(LOCALES_DIR, lang);
    const expected = new Set<string>();
    for (const mod of modules) {
      expected.add(`${mod.ns}.ts`);
      if (writeIfChanged(join(dir, `${mod.ns}.ts`), renderModule(mod, lang, store, stats))) written += 1;
    }
    // 命名空间被删掉后,清理遗留的生成文件(只动带生成头的 .ts)。
    if (existsSync(dir)) {
      for (const name of readdirSync(dir)) {
        const file = join(dir, name);
        if (!name.endsWith(".ts") || expected.has(name)) continue;
        if (readFileSync(file, "utf8").startsWith(HEADER_PREFIX)) unlinkSync(file);
      }
    }
  }
  console.log(`[i18n] ${MT_LANGS.length} 种语言 × ${modules.length} 个命名空间,写入 ${written} 个文件,套用译文 ${stats.applied} 条`);
}

const command = process.argv[2];
if (command === "extract") extract();
else if (command === "generate") generate();
else {
  console.error("用法:bun scripts/i18n-messages.ts <extract|generate>");
  process.exit(2);
}
