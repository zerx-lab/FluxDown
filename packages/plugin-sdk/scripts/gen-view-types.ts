// Generates src/types/view.d.ts from native/protocol/src/plugin_view_schema.json.
// `--check` compares with the committed file and exits 1 on drift.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const SCHEMA = new URL("../../../native/protocol/src/plugin_view_schema.json", import.meta.url);
const OUT = new URL("../src/types/view.d.ts", import.meta.url);

interface PropSpec {
  type: string;
  enum?: string;
  required?: boolean;
  nullable?: boolean;
  default?: unknown;
  min?: number;
  max?: number;
  maxItems?: number;
  format?: string;
  item?: { fields: Record<string, PropSpec>; additional?: boolean };
}
interface EventSpec {
  payload?: Record<string, string>;
  debounceMs?: number;
}
interface KindSpec {
  doc?: string;
  children?: boolean;
  keyedProp?: string;
  props: Record<string, PropSpec>;
  events?: Record<string, EventSpec>;
}
interface Schema {
  version: number;
  limits: Record<string, number>;
  enums: Record<string, string[]>;
  kinds: Record<string, KindSpec>;
}

const schema: Schema = JSON.parse(readFileSync(SCHEMA, "utf8"));

const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const enumName = (key: string) => pascal(key);
const union = (values: string[]) => values.map((v) => JSON.stringify(v)).join(" | ");

function tsType(spec: PropSpec, indent: string): string {
  let base: string;
  if (spec.format === "imageSource") {
    base = [
      "`data:image/png;base64,${string}`",
      "`data:image/jpeg;base64,${string}`",
      "`data:image/webp;base64,${string}`",
      "`flux-image:${string}`",
    ].join(" | ");
  } else {
    switch (spec.type) {
      case "string":
        base = "string";
        break;
      case "bool":
        base = "boolean";
        break;
      case "number":
      case "int":
        base = "number";
        break;
      case "enum":
        if (!spec.enum) throw new Error("enum prop without enum name");
        base = enumName(spec.enum);
        break;
      case "array": {
        const item = spec.item;
        if (!item) throw new Error("array prop without item");
        const fields = Object.entries(item.fields)
          .map(([k, f]) => `${indent}  ${k}${f.required ? "" : "?"}: ${tsType(f, `${indent}  `)};`)
          .join("\n");
        const extra = item.additional ? `${indent}  [column: string]: unknown;\n` : "";
        base = `Array<{\n${fields}\n${extra}${indent}}>`;
        break;
      }
      default:
        throw new Error(`unsupported prop type ${spec.type}`);
    }
  }
  return spec.nullable ? `${base} | null` : base;
}

function propDoc(spec: PropSpec): string {
  const bits: string[] = [];
  if (spec.default !== undefined) bits.push(`default ${JSON.stringify(spec.default)}`);
  if (spec.min !== undefined || spec.max !== undefined) {
    bits.push(`range ${spec.min ?? "-∞"}..${spec.max ?? "∞"}`);
  }
  if (spec.maxItems !== undefined) bits.push(`at most ${spec.maxItems} items`);
  if (spec.format === "httpUrl") bits.push("http(s) URLs only");
  if (spec.format === "imageDataUri") bits.push("data:image/(png|jpeg|webp);base64, only");
  if (spec.format === "imageSource") bits.push("data:image/(png|jpeg|webp);base64, or flux-image:<uuid>");
  return bits.length ? `  /** ${bits.join("; ")} */\n` : "";
}

function render(): string {
  const out: string[] = [];
  out.push(
    "// AUTO-GENERATED by scripts/gen-view-types.ts from native/protocol/src/plugin_view_schema.json.",
    "// Do not edit by hand; run `bun run gen`.",
    `// Schema version ${schema.version}; limits: ${JSON.stringify(schema.limits)}.`,
    "",
  );
  for (const [key, values] of Object.entries(schema.enums)) {
    out.push(`export type ${enumName(key)} = ${union(values)};`);
  }
  out.push(
    "",
    "/** A plain view node as produced by `flux.ui.h` / the JSX runtime. */",
    "export interface ViewNode {",
    "  k: string;",
    "  p: Record<string, unknown>;",
    "  c: ViewNode[];",
    "}",
    "",
    "/** Anything accepted as a child: nodes, nested arrays; `null`/`false`/`undefined` are dropped. */",
    "export type ViewChild = ViewNode | null | false | undefined | ViewChild[];",
    "",
    "/** Props every node accepts. `key` keeps node identity stable across renders (also table rows / list items). */",
    "export interface CommonProps {",
    "  key?: string | number;",
    "}",
    "",
  );
  const names: [string, string][] = [];
  for (const [kind, spec] of Object.entries(schema.kinds)) {
    const name = `${pascal(kind)}Props`;
    names.push([kind, name]);
    const doc = [spec.doc ?? ""];
    if (spec.events && Object.keys(spec.events).length) {
      const evs = Object.entries(spec.events).map(([ev, e]) => {
        const payload = e.payload
          ? `{${Object.entries(e.payload).map(([k, t]) => `${k}: ${t}`).join(", ")}}`
          : "";
        const debounce = e.debounceMs ? `, debounced ${e.debounceMs} ms` : "";
        return `${ev}${payload}${debounce}`;
      });
      doc.push(`Events (delivered to the view's \`event\` handler): ${evs.join("; ")}.`);
    }
    out.push("/**", ...doc.filter(Boolean).map((l) => ` * ${l}`), " */");
    out.push(`export interface ${name} extends CommonProps {`);
    for (const [prop, p] of Object.entries(spec.props)) {
      const optional = p.required ? "" : "?";
      const doc = propDoc(p);
      out.push(`${doc}  ${prop}${optional}: ${tsType(p, "  ")};`);
    }
    out.push(spec.children ? "  children?: ViewChild;" : "  children?: never;", "}", "");
  }
  out.push("/** JSX intrinsic elements: one lowercase tag per node kind. */", "export interface ViewIntrinsicElements {");
  for (const [kind, name] of names) out.push(`  ${kind}: ${name};`);
  out.push("}", "");
  out.push("/** Node kind names. */", `export type ViewKind = keyof ViewIntrinsicElements;`, "");
  return out.join("\n");
}

const content = render();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
  if (current !== content) {
    console.error("src/types/view.d.ts is out of date; run `bun run gen`.");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, content);
}
